def build(name, scenario):
    data = copy.deepcopy(BASE)
    data["meta"] = META.get(name, {})
    data["goal"] = scenario["goal"]
    data["assistant_identity"] = scenario["identity"]
    data["scene"] = scenario["scene"]
    data["functions"] = scenario["functions"]
    data["safety"] = scenario["safety"]
    data["examples"] = {
        "first_open": scenario["first_open"],
        "first_generated_function": scenario["first_generated_function"],
        **copy.deepcopy(PROCESS_EXAMPLES),
    }
    return data


def safety(scope, privacy, boundary=None):
    s = copy.deepcopy(BASE["safety"])
    s["scope"] = scope
    s["privacy"] = privacy
    if boundary:
        s["boundary"] = boundary
    return s


