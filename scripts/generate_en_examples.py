def build(name, data):
    spec = copy.deepcopy(BASE)
    spec["meta"] = META[name]
    spec["goal"] = GOAL % data["scene_what"]
    spec["assistant_identity"] = {
        "fill_rule": BASE["assistant_identity"]["fill_rule"],
        "what": data["what"],
        "why": data["why"],
        "how": data["how"],
    }
    spec["scene"] = {
        "fill_rule": BASE["scene"]["fill_rule"],
        "what": data["scene_what"],
        "why": data["scene_why"],
        "how": data["scene_how"],
    }
    ability, checkpoint = EN_PLAN[name]
    spec["training_plan"] = {
        "fill_rule": BASE["training_plan"]["fill_rule"],
        "ability": ability,
        "cadence": "About %d minutes a day, two weeks to start" % META[name]["daily_minutes"],
        "checkpoint": checkpoint,
        "status": "active",
    }
    spec["functions"] = data["functions"]
    spec["safety"] = {
        "scope": data["scope"],
        "crisis": BASE["safety"]["crisis"],
        "privacy": data["privacy"],
        "boundary": data["boundary"],
    }
    names = ", ".join(f["name"] for f in data["functions"])
    spec["examples"]["first_open"] = {
        "desc": "The user's opening message on first use",
        "user": data["first_user"],
        "ai_should": "Confirm the date → confirm assistant_identity / scene → fill training_plan → generate and confirm functions (%s) → output the complete archive JSON" % names,
    }
    spec["examples"]["first_generated_function"] = {
        "desc": "How a single function should look when first generated",
        "sample": copy.deepcopy(data["functions"][0]),
    }
    return spec


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    for name, data in SCENARIOS.items():
        path = os.path.join(OUT_DIR, name + ".json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(build(name, data), f, ensure_ascii=False, indent=4)
            f.write("\n")
        print("wrote", path)


if __name__ == "__main__":
    main()
